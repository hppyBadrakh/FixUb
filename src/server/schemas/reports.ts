// Citizen-side input schemas: create report, me-too, verdict, flag.
// They mirror the checks in src/lib/domain/actions.ts, which stays the reference for the rules.
import { z } from "zod";
import { inServiceArea } from "@/lib/domain/geo";
import { LIMITS } from "@/lib/meta";
import type { FlagReason } from "@/lib/types";
import { districtSchema, idSchema, latSchema, lngSchema } from "./common";

/**
 * The demo requires a camera photo on every report. Photo upload to R2 arrives after the first
 * database-backed report flow (B06 before B10): set this to false until then.
 */
export const REQUIRE_PHOTO = true;

/** Error codes returned as field messages. The UI maps them to Mongolian/English text. */
export const ERROR_CODES = {
  descriptionLength: "description_length",
  outOfArea: "out_of_area",
  photoRequired: "photo_required",
  tooManyPhotos: "too_many_photos",
} as const;

export const createReportSchema = z
  .object({
    category: idSchema,
    subcategory: idSchema,
    description: z
      .string()
      .trim()
      .min(LIMITS.descriptionMin, ERROR_CODES.descriptionLength)
      .max(LIMITS.descriptionMax, ERROR_CODES.descriptionLength),
    lng: lngSchema,
    lat: latSchema,
    /** GPS accuracy in metres, when the point came from "Use my location". */
    accuracyM: z.number().nonnegative().max(100_000).optional(),
    addressHint: z.string().trim().max(200).default(""),
    district: districtSchema,
    photoIds: z
      .array(idSchema)
      .min(REQUIRE_PHOTO ? 1 : 0, ERROR_CODES.photoRequired)
      .max(LIMITS.photosMax, ERROR_CODES.tooManyPhotos),
    /** Idempotency key generated by the report form: a double submit creates one report. */
    clientRequestId: z.string().trim().min(8).max(64),
  })
  .superRefine((v, ctx) => {
    if (!inServiceArea(v)) {
      ctx.addIssue({ code: "custom", path: ["lng"], message: ERROR_CODES.outOfArea });
    }
  });
export type CreateReportInput = z.infer<typeof createReportSchema>;

/** Toggles the signed-in user's "me too" on a report. */
export const meTooSchema = z.object({ reportId: idSchema });
export type MeTooInput = z.infer<typeof meTooSchema>;

/** "Is it actually fixed?" Send `null` to clear the user's earlier answer. */
export const verdictSchema = z.object({
  reportId: idSchema,
  verdict: z.enum(["fixed", "not_fixed"]).nullable(),
});
export type VerdictInput = z.infer<typeof verdictSchema>;

export const FLAG_REASONS = ["spam", "offensive", "personal_info", "not_infrastructure", "other"] as const;

// Fails to compile if the list drifts from `FlagReason` in src/lib/types.ts.
export const _flagReasonsMatch: [FlagReason] extends [(typeof FLAG_REASONS)[number]]
  ? [(typeof FLAG_REASONS)[number]] extends [FlagReason]
    ? true
    : never
  : never = true;

export const flagSchema = z.object({
  reportId: idSchema,
  reason: z.enum(FLAG_REASONS),
  details: z.string().trim().max(500).default(""),
});
export type FlagInput = z.infer<typeof flagSchema>;
